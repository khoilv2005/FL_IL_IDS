"""Embed the current training source in one uploadable Kaggle Python file."""
import base64
import hashlib
import io
from pathlib import Path
import zipfile


def main():
    root = Path(__file__).resolve().parents[1]
    files = [root / 'train_incremental_kaggle.py', root / 'configs/denice_appliance.json']
    for directory in ('fed_learning', 'appliance'):
        files.extend((root / directory).rglob('*.py'))
    buffer = io.BytesIO()
    with zipfile.ZipFile(buffer, 'w', zipfile.ZIP_DEFLATED) as archive:
        for path in sorted(files):
            archive.writestr(path.relative_to(root).as_posix(), path.read_bytes())
    payload = buffer.getvalue()
    digest = hashlib.sha256(payload).hexdigest()
    encoded = base64.b85encode(payload).decode('ascii')
    bootstrap = '''# Generated by tools/package_denice_single_file.py; source-only bundle.
# Set DENICE_* environment variables before running this file.
import base64, hashlib, io, os, tempfile, zipfile
from pathlib import Path
_payload = base64.b85decode(PAYLOAD)
assert hashlib.sha256(_payload).hexdigest() == DIGEST, 'Corrupted source bundle'
_source = Path(tempfile.mkdtemp(prefix='denice-overlay-resume-'))
with zipfile.ZipFile(io.BytesIO(_payload)) as _archive:
    _archive.extractall(_source)
os.environ['DENICE_CODE_DIR'] = str(_source)
print('Bundled training source SHA256:', DIGEST, flush=True)
_entry = _source / 'train_incremental_kaggle.py'
exec(compile(_entry.read_bytes(), str(_entry), 'exec'),
     {'__name__': '__main__', '__file__': str(_entry)})
'''.replace('PAYLOAD', repr(encoded)).replace('DIGEST', repr(digest))
    output = root / 'output/single_file/train_incremental_kaggle.py'
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(bootstrap, encoding='utf-8')
    compile(bootstrap, str(output), 'exec')
    print(f'{output}\n{output.stat().st_size} bytes; embedded source SHA256 {digest}')


if __name__ == '__main__':
    main()
